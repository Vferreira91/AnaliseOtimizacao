-- Schema base do sistema de pedidos.
--
-- Regra do projeto: aqui só existem as chaves primárias (que o Postgres indexa
-- automaticamente). Nenhuma FK recebe índice e não há UNIQUE em colunas comuns,
-- porque UNIQUE também cria índice. Os índices dos experimentos ficam em
-- db/indices/criar.sql e db/indices/remover.sql, para o cenário "sem índice" ser real.

CREATE TABLE categoria (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    descricao TEXT
);

CREATE TABLE produto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150)   NOT NULL,
    preco         NUMERIC(12, 2) NOT NULL CHECK (preco >= 0),
    estoque       INTEGER        NOT NULL CHECK (estoque >= 0),
    categoria_id  BIGINT         NOT NULL REFERENCES categoria (id),
    atualizado_em TIMESTAMP      NOT NULL DEFAULT now()
);

CREATE TABLE cliente (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(150) NOT NULL,
    email     VARCHAR(150) NOT NULL,
    cidade    VARCHAR(100) NOT NULL,
    uf        CHAR(2)      NOT NULL,
    criado_em TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE pedido (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT         NOT NULL REFERENCES cliente (id),
    data_pedido TIMESTAMP      NOT NULL,
    status      VARCHAR(20)    NOT NULL
        CHECK (status IN ('PENDENTE', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
    valor_total NUMERIC(14, 2) NOT NULL DEFAULT 0
);

CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL REFERENCES pedido (id),
    produto_id     BIGINT         NOT NULL REFERENCES produto (id),
    quantidade     INTEGER        NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12, 2) NOT NULL CHECK (preco_unitario >= 0)
);
